# Cumulative learning for Ridge regression
def cumulative_ridge(X, y, model, n_splits=5):
    maes = []
    mses = []

    for fold in range(n_splits):
        # Split the data into training and validation sets
        X_train_split, X_val_split, y_train_split, y_val_split = train_test_split(X, y, test_size=0.2, random_state=None)

        # Fit the model on the current training set
        model.fit(X_train_split, y_train_split)

        # Make predictions on the validation set
        predictions = model.predict(X_val_split)

        # Evaluate the model
        mae, mse = evaluate_model(y_val_split, predictions)
        maes.append(mae)
        mses.append(mse)  # Append MSE for averaging later

        # Print the errors for the current fold
        print(f"Fold {fold + 1} - Mean Absolute Error: {mae}, Mean Squared Error: {mse}")

    # Return average MAE, MSE, and last fold MAE
    return np.mean(maes), np.mean(mses), maes[-1]

# Perform cumulative learning for the default Ridge regression model
print("\nCumulative Ridge Regression Model Validation Results:")

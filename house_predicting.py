# Function to evaluate and print MAE and MSE
def evaluate_model(y_true, predictions):
    mae = mean_absolute_error(y_true, predictions)
    mse = mean_squared_error(y_true, predictions)
    return mae, mse

# Ensure that y_train is aligned with the number of samples in X_train
